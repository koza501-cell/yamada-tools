export const getToolById = (id: string): Tool | undefined => {
  return allTools.find(t => t.id === id);
};

export const getToolsByCategory = (category: Tool["category"]): Tool[] => {
  switch (category) {
    case "pdf":
      return pdfTools;
    case "document":
      return documentTools;
    case "convert":
      return convertTools;
    case "image":
      return imageTools;
    case "generator":
      return generatorTools;
    case "finance":
      return financeTools;
    default:
      return [];
  }
};

